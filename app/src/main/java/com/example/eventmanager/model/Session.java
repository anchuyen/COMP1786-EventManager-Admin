package com.example.eventmanager.model;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

/**
 * One session (activity) that takes place during an event - coursework feature (b).
 * <p>
 * Relationship: one Event has many Sessions. {@link #getEventId()} is the foreign key
 * that links the session to its event. When the event is deleted, SQLite deletes its
 * sessions automatically (ON DELETE CASCADE).
 * <p>
 * Same immutable design as {@link Event}.
 */
public class Session {

    /** ID used for a new session that has not been saved to the database yet. */
    public static final long NO_ID = 0;

    /** Auto-generated by SQLite (required). */
    private final long id;
    /** ID of the event this session belongs to (required). */
    private final long eventId;
    /** Required. */
    private final String name;
    /** Required, stored as "HH:mm" (24-hour), so sorting the text also sorts by time. */
    private final String time;
    /** Optional. */
    @Nullable
    private final String speaker;
    /** Optional. */
    @Nullable
    private final String room;
    /** Chosen from a fixed list, so it can never be invalid. */
    private final SessionType type;
    /** Optional. */
    @Nullable
    private final String description;

    public Session(long id,
                   long eventId,
                   @NonNull String name,
                   @NonNull String time,
                   @Nullable String speaker,
                   @Nullable String room,
                   @NonNull SessionType type,
                   @Nullable String description) {
        this.id = id;
        this.eventId = eventId;
        this.name = name;
        this.time = time;
        this.speaker = emptyToNull(speaker);
        this.room = emptyToNull(room);
        this.type = type;
        this.description = emptyToNull(description);
    }

    /** Returns a copy of this session with a different ID (used after an insert). */
    @NonNull
    public Session withId(long newId) {
        return new Session(newId, eventId, name, time, speaker, room, type, description);
    }

    /** Returns a copy attached to another event (used when restoring after Undo). */
    @NonNull
    public Session withEventId(long newEventId) {
        return new Session(id, newEventId, name, time, speaker, room, type, description);
    }

    @Nullable
    private static String emptyToNull(@Nullable String value) {
        if (value == null) {
            return null;
        }
        String trimmed = value.trim();
        return trimmed.isEmpty() ? null : trimmed;
    }

    // =====================================================================
    // Getters
    // =====================================================================

    public long getId() {
        return id;
    }

    public long getEventId() {
        return eventId;
    }

    @NonNull
    public String getName() {
        return name;
    }

    @NonNull
    public String getTime() {
        return time;
    }

    @Nullable
    public String getSpeaker() {
        return speaker;
    }

    @Nullable
    public String getRoom() {
        return room;
    }

    @NonNull
    public SessionType getType() {
        return type;
    }

    @Nullable
    public String getDescription() {
        return description;
    }
}
